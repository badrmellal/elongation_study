print(g)

# ---- k=2 PV round trip (explains the sign flip) and per-reciter RB consistency ----
two_g, two_l, pos, cells = [], [], 0, 0
for m in ["tarteel", "M0", "M1", "M2"]:
    d = rows(H / "results" / m / "observations.jsonl")
    rt = rows(H / "results" / f"rt_{m}" / "observations.jsonl")
    for key, row in rt.items():
        d[key].update(row)
    gl, lo = [], []
    for n in P:
        gl.append(np.mean([r[("global_rt", 2.0)] - r[("sham_pv_global", 1.0)] for (rc, v), r in d.items() if rc == n and ("global_rt", 2.0) in r]))
        lo.append(np.mean([r[("nucleus_rt", 2.0)] - r[("sham_pv_local", 1.0)] for (rc, v), r in d.items() if rc == n and ("nucleus_rt", 2.0) in r]))
        c = np.mean([r[("nucleus_rb", 4.0)] - r[("global_rb", 4.0)] for (rc, v), r in d.items() if rc == n and ("nucleus_rb", 4.0) in r and ("global_rb", 4.0) in r])
        pos += c > 0; cells += 1
    two_g.append(np.mean(gl)); two_l.append(np.mean(lo))
with open(H / "figs" / "recast_numbers.tex", "a") as fh:
    fh.write(f"\\newcommand{{\\RtTwoGMin}}{{{min(two_g):.2f}}}\n\\newcommand{{\\RtTwoGMax}}{{{max(two_g):.2f}}}\n"
             f"\\newcommand{{\\RtTwoLMin}}{{{min(two_l):.2f}}}\n\\newcommand{{\\RtTwoLMax}}{{{max(two_l):.2f}}}\n"
             f"\\newcommand{{\\RbCellsPos}}{{{pos}}}\n\\newcommand{{\\RbCells}}{{{cells}}}\n")
print("k2 global", [round(x, 3) for x in two_g], "local", [round(x, 3) for x in two_l], "RB positive cells", pos, "/", cells)
