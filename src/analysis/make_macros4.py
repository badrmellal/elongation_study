for m, _ in MODELS:
    d = rows(m); s = crossed(d, lambda r: C("nucleus_rb", "global_rb", 6.0)(r) - C("nucleus_rb", "global_rb", 4.0)(r)); fs.append((s["mean"], s["ci95"][0]))
with open(H / "figs" / "recast_numbers4.tex", "a") as fh:
    fh.write(f"\\newcommand{{\\FourSixMin}}{{{s3(min(x for x, _ in fs))}}}\n\\newcommand{{\\FourSixMax}}{{{s3(max(x for x, _ in fs))}}}\n")
print("k4->k6 steps", [(round(a,3), round(b,3)) for a, b in fs], "any lower bound > 0:", any(b > 0 for _, b in fs))
